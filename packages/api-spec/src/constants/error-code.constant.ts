  AUTH_ALERT_FORBIDDEN: "AUTH_ALERT_FORBIDDEN",
  AUTH_ALERT_INVALID_PAYLOAD: "AUTH_ALERT_INVALID_PAYLOAD",
  AUTH_ALERT_INVALID_GUEST_TOKEN: "AUTH_ALERT_INVALID_GUEST_TOKEN",
  AUTH_ALERT_SESSION_EXPIRED: "AUTH_ALERT_SESSION_EXPIRED",
  AUTH_CONFIRM_RESET_DATA: "AUTH_CONFIRM_RESET_DATA",
  AUTH_WARN_GUEST_LIMIT: "AUTH_WARN_GUEST_LIMIT",
  AUTH_FIELD_TOKEN_REQUIRED: "AUTH_FIELD_TOKEN_REQUIRED",
  AUTH_FATAL_CONFIG_ERROR: "AUTH_FATAL_CONFIG_ERROR",

  // 2. 메모 도메인 (MEMO)
  MEMO_FIELD_REQUIRED: "MEMO_FIELD_REQUIRED",
  MEMO_FIELD_EMPTY: "MEMO_FIELD_EMPTY",
  MEMO_FIELD_EXCEEDED: "MEMO_FIELD_EXCEEDED",
  MEMO_WARN_NOT_FOUND: "MEMO_WARN_NOT_FOUND",
  MEMO_INFO_RESTORED: "MEMO_INFO_RESTORED",

  // 3. 카테고리 도메인 (CATEGORY)
  CATEGORY_FIELD_REQUIRED: "CATEGORY_FIELD_REQUIRED",
  CATEGORY_FIELD_EXCEEDED: "CATEGORY_FIELD_EXCEEDED",
  CATEGORY_FIELD_INVALID: "CATEGORY_FIELD_INVALID",
