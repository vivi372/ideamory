  OGP_ERROR_PARSE_FAILED: "OGP_ERROR_PARSE_FAILED",
  OGP_WARN_TIMEOUT: "OGP_WARN_TIMEOUT",

  // 5. 공통 입력 필드 도메인 (COMMON)
  COMMON_FIELD_REQUIRED: "COMMON_FIELD_REQUIRED",
  COMMON_FIELD_FORMAT: "COMMON_FIELD_FORMAT",
